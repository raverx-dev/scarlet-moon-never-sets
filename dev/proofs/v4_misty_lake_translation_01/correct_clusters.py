def grid(text):return [list(r) for r in text.strip('\n').splitlines()]
def blank(name,c='.'):
 m=old[name]['matrix'];return [[c]*m['width'] for _ in range(m['height'])]
def put(dst,src,x,y,colors=None,mirror=False):
 rows=grid(src) if isinstance(src,str) else src
 width=max(map(len,rows))
 for yy,row in enumerate(rows):
  rr=list(row)+['.']*(width-len(row))
  if mirror:rr=rr[::-1]
  for xx,ch in enumerate(rr):
   if ch!='.' and 0<=y+yy<len(dst) and 0<=x+xx<len(dst[0]):dst[y+yy][x+xx]=colors.get(ch,ch) if colors else ch
def finish(name,g):out[name]={'width':len(g[0]),'height':len(g),'rows':[''.join(r) for r in g]}

