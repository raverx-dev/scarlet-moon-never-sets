class Grid:
 def __init__(self,w,h,c='.'):
  self.w,self.h=w,h; self.p=[list(c*w) for _ in range(h)]
 def put(self,x,y,rows,flip=False,swap=None):
  if isinstance(rows,str): rows=rows.strip('\n').splitlines()
  if isinstance(rows,Grid): rows=rows.rows()
  for j,row in enumerate(rows):
   if flip:row=row[::-1]
   if swap:row=''.join(swap.get(c,c) for c in row)
   for i,c in enumerate(row):
    if c!='.' and 0<=x+i<self.w and 0<=y+j<self.h:self.p[y+j][x+i]=c
 def box(self,x,y,w,h,c):
  self.put(x,y,[c*w]*h)
 def rows(self):return [''.join(r) for r in self.p]
 def copy(self):
  g=Grid(self.w,self.h);g.p=[r[:] for r in self.p];return g

