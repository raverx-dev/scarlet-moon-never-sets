"""Serialize hand-authored native token grids. No reference sampling or vector drawing.

Grids are the editable artwork. Helpers only place/reflect explicit rows, or expand
solid rectangular fields and authored run lengths. No random/procedural textures.
The JSON produced here is pasted into RoboPixel; compositions use its readbacks.
"""
from pathlib import Path
