def grid(text):
 rows=text.strip('\n').splitlines();w=max(map(len,rows));return [r.ljust(w,'.') for r in rows]
def put(dest,rows,x,y):
 for j,row in enumerate(rows):
  for i,c in enumerate(row):
   if c!='.' and 0<=y+j<len(dest) and 0<=x+i<len(dest[0]):dest[y+j][x+i]=c
def asset(name,text):A[name]=grid(text)
def assembled(name,w,h,bg,placements):
 a=[list(bg*w) for _ in range(h)]
